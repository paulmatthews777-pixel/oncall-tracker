const fs=require('node:fs'),assert=require('node:assert/strict');
const wrapper=fs.readFileSync('demo.html','utf8');
assert.match(wrapper,/srcdoc=/,'wrapper contains its own isolated Demo so it works offline');
assert(wrapper.includes('DEMO MODE · Fictional data'),'embedded Demo includes its safety bootstrap');
assert.match(wrapper,/sandbox="allow-scripts"/,'Demo iframe cannot access the app origin or navigate the parent');
const encoded=wrapper.match(/srcdoc="([^"]*)"/);
assert(encoded,'embedded Demo must exist');
const app=encoded[1].replace(/&quot;/g,'"').replace(/&#x27;/g,"'").replace(/&lt;/g,'<').replace(/&gt;/g,'>').replace(/&amp;/g,'&');
assert.match(app,/connect-src 'none'/,'Demo blocks network connections');
assert.match(app,/form-action 'none'/,'Demo blocks form submissions');
assert.match(app,/DEMO MODE · Fictional data/,'Demo must be visibly labelled');
assert(!/https:\/\/fonts\.googleapis\.com/.test(app),'Demo does not contact Google Fonts');
assert(!/<script\s+src=/i.test(app),'Demo does not depend on separate scripts');
assert.match(app,/Alex Example/,'Demo uses fictional people');
assert(!app.includes('Paul Matthews'),'Demo must not show the real user name');
assert(!app.includes('14.3947'),'Demo must not use the real payslip rate');
assert.match(app,/APP_VERSION='v60'/,'Demo bundle matches the app release');
const sw=fs.readFileSync('sw.js','utf8');
assert(sw.includes("'demo.html'"),'offline cache includes the self-contained Demo');
console.log('demo bundle PASS');
