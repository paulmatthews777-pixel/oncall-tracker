const assert = require('node:assert'), http = require('node:http'), fs = require('node:fs'), os = require('node:os'), path = require('node:path');
const tmp = fs.mkdtempSync(path.join(os.tmpdir(), 'ab-'));
process.env.AUTOBOOK_STATE = path.join(tmp, 'state.json');
process.env.AUDIT_DIR = path.join(tmp, 'audit');
process.env.PC_KEY_FILE = path.join(tmp, 'key.txt'); fs.writeFileSync(process.env.PC_KEY_FILE, 'SECRETKEY123');
