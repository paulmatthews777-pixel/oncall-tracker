const mkFw = (res) => ({n: 0, v: 0, bookRanges: async function (r, rec, step) { this.n++; rec.confirmations.push('Impact: Short 1 Crewing Total'); step('book', 'x'); return res; }, verifyRanges: async function () { this.v++; return {ok: false}; }});
